CREATE TABLE employee (
    id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    first_name     VARCHAR2(100) NOT NULL,
    last_name      VARCHAR2(100) NOT NULL,
    date_of_birth  DATE,
    created_at     TIMESTAMP DEFAULT ON NULL SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT employee_pk PRIMARY KEY (id)
);

COMMENT ON TABLE  employee               IS 'Employees';
COMMENT ON COLUMN employee.id            IS 'Primary key (identity)';
COMMENT ON COLUMN employee.first_name    IS 'First name';
COMMENT ON COLUMN employee.last_name     IS 'Last name';
COMMENT ON COLUMN employee.date_of_birth IS 'Date of birth';
COMMENT ON COLUMN employee.created_at    IS 'Record creation time, UTC';
